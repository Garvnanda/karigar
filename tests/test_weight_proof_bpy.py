"""Phase 9: weight-maths proof. Mesh volume (what every weight uses) vs exact formula volume.

Plain bands go through the real weight path (`geometry.gold_volume`); their exact volume is
Pappus: V = 2π · x̄ · A, with the superellipse cross-section area A = 4ab·Γ(1+1/n)²/Γ(1+2/n)
and x̄ = inner radius + a. The disc pendant's body is an oblate ellipsoid, V = 4/3·π·R²·c.
Error must stay < 0.5%. `KARIGAR_WRITE_PROOF=1` also writes docs/weight-proof.md.
"""
import math
import os
from pathlib import Path

import pytest

from karigar.core import gold as G
from karigar.core.calibration import CalibrationStore
from karigar.packs.jewellery.schema import DesignSpec

pytest.importorskip("bpy")
from karigar.packs.jewellery import geometry  # noqa: E402

DOC = Path(__file__).resolve().parents[1] / "docs" / "weight-proof.md"


def superellipse_area(a, b, n):
    return 4 * a * b * math.gamma(1 + 1 / n) ** 2 / math.gamma(1 + 2 / n)


def band_exact(inner_d, width, thick, profile):
    n_in, n_out = geometry.PROFILE_EXP[profile]
    assert n_in == n_out                       # symmetric section: centroid at the section centre
    a, b = thick / 2, width / 2
    return 2 * math.pi * (inner_d / 2 + a) * superellipse_area(a, b, n_in)


BANDS = [  # (label, inner_d, width, thickness, profile)
    ("Comfort band, size 8 (16.0 mm)", 16.0, 3.0, 1.8, "comfort"),
    ("Comfort band, size 14 (17.9 mm)", 17.9, 3.5, 1.8, "comfort"),
    ("Comfort band, size 22 (20.4 mm)", 20.4, 4.5, 2.2, "comfort"),
    ("Flat band, size 14 (17.9 mm)", 17.9, 4.0, 1.6, "flat"),
]


def rows():
    out = []
    for label, d, w, t, prof in BANDS:
        spec = DesignSpec(name=label, piece_type="ring", karat=22, profile=prof,
                          inner_d_mm=d, width_mm=w, thickness_mm=t)
        out.append((label, geometry.gold_volume(spec, 1.0), band_exact(d, w, t, prof)))
    R, c = 9.0, 0.6
    ob = geometry.sphere((0, 0, 0), (R, R, c), "coin", 96, 36)   # the disc pendant's body
    out.append(("Disc pendant body, 18 mm × 1.2 mm", geometry.mesh_volume(ob), 4 / 3 * math.pi * R * R * c))
    return out


def test_mesh_volume_matches_exact_formulas_within_half_a_percent():
    table = rows()
    lines = ["# Weight-maths proof", "",
             "Generated by `tests/test_weight_proof_bpy.py` (`KARIGAR_WRITE_PROOF=1`). "
             "Mesh volume is what every Karigar weight uses; exact volume is the closed-form formula.", "",
             "| Shape | Mesh volume (mm³) | Exact volume (mm³) | Error | 22K weight (g) |",
             "|---|---|---|---|---|"]
    for label, mesh, exact in table:
        err = (mesh - exact) / exact * 100
        assert abs(err) < 0.5, (label, mesh, exact, err)
        lines.append(f"| {label} | {mesh:.2f} | {exact:.2f} | {err:+.3f}% | {mesh / 1000 * G.density(22):.3f} |")
    if os.environ.get("KARIGAR_WRITE_PROOF") == "1":
        DOC.write_text("\n".join(lines) + "\n")


def test_calibration_learns_a_workshop_loss(tmp_path):
    """After 3 recorded casts, predictions use the learned loss and its spread, not the default."""
    cal = CalibrationStore(tmp_path / "cal.json")
    assert cal.loss_pct("w1") == 3.0
    default_tol = cal.tolerance("w1")
    for designed, actual in ((10.0, 9.55), (8.0, 7.64), (12.0, 11.46)):   # 4.5% real loss
        cal.record("w1", designed, actual)
    assert cal.loss_pct("w1") == pytest.approx(4.5)
    assert cal.tolerance("w1") != default_tol
    assert CalibrationStore(tmp_path / "cal.json").loss_pct("w1") == pytest.approx(4.5)   # persisted
    assert cal.loss_pct("other") == 3.0                                                   # per workshop
